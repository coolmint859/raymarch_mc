use std::collections::HashMap;

use glam::Vec4;
use rayon::iter::{IntoParallelIterator, ParallelIterator};

use crate::utils::SdfGenerator;

/// Data struct holding information about character glyphs for use during rendering
#[derive(Clone, Debug)]
pub struct CharacterGlyph {
    /// The bounding box of the glyph in the atlas
    pub uv_bounds: glam::Vec4,
    /// The layout bounds of the character relative to the cursor
    pub plane_bounds: glam::Vec4,
    /// How far to advance the cursor after placing this character
    pub advance: f32,
}

/// Contains the raw bitmap information about a specific glyph
/// 
/// This is a temporary struct generated by rayon threads.
pub struct Glyph {
    ch: char,
    metrics: fontdue::Metrics,
    bitmap: Bitmap
}

/// A character bitmap
pub struct Bitmap {
    /// the coverage vector of the bitmap
    pub data: Vec<u8>,
    // the height of the bitmap
    pub width: u32,
    /// the width of the bitmap
    pub height: u32,
}

pub enum AtlasType {
    /// Generate an SDF atlas
    SDF { radius: f32 },
    /// Generate a bitmap atlas
    BitMap
}

/// Config struct for generating font atlases
pub struct AtlasConfig {
    pub font: fontdue::Font,
    pub size: u32,
    pub scale: f32,
    pub spacing: u32,
    pub ty: AtlasType
}

/// Generate a signed distance field (sdf) font atlas by rasterizing a ttf font
/// 
/// * 'font' - the font containing the glyph metrics
/// * 'size' - the size of the sdf atlas in pixels
/// * 'scale' - the size to rasterize the characters with, in pixels per em unit
/// * 'radius' - the signed distance between extreme values in the sdf atlas
pub fn generate_atlas(config: AtlasConfig) -> (HashMap<char, CharacterGlyph>, Vec<u8>) {
    let characters: Vec<u8> = (32u8..127).collect();
    let sdf_glyphs: Vec<Glyph> = characters
        .into_par_iter()
        .map(|u_char| {
            let ch = u_char as char;
            let (metrics, bitmap) = config.font.rasterize(ch, config.scale);

            let raw_bitmap = Bitmap {
                data: bitmap,
                width: metrics.width as u32,
                height: metrics.height as u32
            };

            let bitmap = match &config.ty {
                AtlasType::SDF { radius } => {
                    SdfGenerator::generate(&raw_bitmap, *radius)
                }
                AtlasType::BitMap => raw_bitmap
            };

            Glyph { ch, metrics, bitmap }
        })
        .collect();

    self::blit_glyphs(sdf_glyphs, config)
}

/// blit character glyphs into a font atlas, and convert metrics into glyph bounds
fn blit_glyphs(glyphs: Vec<Glyph>, config: AtlasConfig) -> (HashMap<char, CharacterGlyph>, Vec<u8>){
    let mut atlas_bitmap = vec![0u8; (config.size * config.size) as usize];
    let mut glyph_table = HashMap::new();

    let mut current_x: u32 = 0;
    let mut current_y: u32 = 0;
    let mut max_row_height: u32 = 0;

    for glyph in glyphs {
        // wrap to next row and add 2px spacing between glyphs
        if current_x + glyph.bitmap.width + config.spacing > config.size {
            current_x = 0;
            current_y += max_row_height + config.spacing;
            max_row_height = 0;
        }
        max_row_height = max_row_height.max(glyph.bitmap.height);

        // blit character sdf bitmap into atlas
        for r in 0..glyph.bitmap.height {
            for c in 0..glyph.bitmap.width {
                let src_idx = (r * glyph.bitmap.width + c) as usize;

                let atlas_x = current_x + c;
                let atlas_y = current_y + r;
                let atlas_idx = (atlas_y * config.size + atlas_x) as usize;

                atlas_bitmap[atlas_idx] = glyph.bitmap.data[src_idx];
            }
        }

        // insert character glyph metrics into glyph table
        let uv_bounds = Vec4::new(
            current_x as f32 / config.size as f32,
            current_y as f32 / config.size as f32,
            glyph.bitmap.width as f32 / config.size as f32,
            glyph.bitmap.height as f32 / config.size as f32,
        );

        let r = match config.ty {
            AtlasType::SDF { radius } => radius,
            AtlasType::BitMap => 0.0
        };

        let plane_bounds = Vec4::new(
            glyph.metrics.bounds.xmin as f32 - r,
            glyph.metrics.bounds.ymin as f32 - r,
            glyph.metrics.width as f32 + (r * 2.0),
            glyph.metrics.height as f32 + (r * 2.0)
        );

        glyph_table.insert(glyph.ch, CharacterGlyph {
            plane_bounds,
            uv_bounds,
            advance: glyph.metrics.advance_width
        });

        // advance x coord for next character
        current_x += glyph.bitmap.width + config.spacing;
    }

    (glyph_table, atlas_bitmap)
}